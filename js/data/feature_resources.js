/**
 * Число ресурса на уровне: { value, text } или null.
 * env: { level, pb, mods: {str..cha}, colVal: (колонка) => строка таблицы класса на этом уровне }.
 */
export function resourceCount(res, env) {
  const c = res?.count;
  if (!c) return null;
  const lvl = env.level || 1;
  if (c.fixed != null) return { value: c.fixed, text: `${c.fixed}${c.unit ? ' ' + c.unit : ''}` };
  if (c.col) { const v = env.colVal?.(c.col); return v == null ? null : { value: v, text: String(v) }; }
  if (c.ability) {
    const v = Math.max(c.min ?? -Infinity, (env.mods?.[c.ability] ?? 0) + (c.plus || 0));
    return { value: v, text: String(v) };
  }
  if (c.pb) return { value: env.pb, text: String(env.pb) };
  if (c.perLevel) { const v = c.perLevel * lvl; return { value: v, text: `запас ${v} ${c.unit || ''}`.trim() }; }
  if (c.dice) { const v = (c.plus || 0) + lvl; return { value: v, text: `${v}${c.dice}` }; }
  return null;
}

/** Строка ресурса для заголовка умения: «Ярость (урон +2) — 2 · прод. отдых». */
export function resourceTitle(baseName, res, env) {
  if (!res) return baseName;
  let name = baseName;
  if (res.name?.col) {
    const v = env.colVal?.(res.name.col);
    if (v != null && v !== '—') name += ` (${(res.name.fmt || '{v}').replace('{v}', v)})`;
  }
  const n = resourceCount(res, env);
  return n ? `${name} — ${n.text} · ${REST_LABEL[res.rest] || ''}`.trim() : name;
}
