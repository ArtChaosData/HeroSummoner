// Schema (see docs/reviews/2026-09-08_warlock-and-tce-optional-features.md for why this exists):
// - A plain string  = base PHB feature. Always granted automatically at that level.
// - An object       = optional/variant feature that requires a table decision, shape:
//     { name: 'Название', optional: true, source: 'TCE', replaces?: 'Название базового умения' }
//   `replaces` is set only when the optional feature is a straight swap for a base feature
//   listed at the SAME level in this same table (so a UI can render them as one either/or
//   choice instead of two features granted at once). When `replaces` is absent, the optional
//   feature is additive (Мастер may allow it alongside the base progression).
//
// IMPORTANT: this file is not yet imported by any screen (see backend review) — fix data here
// BEFORE wiring it into a level-up/character-sheet screen, not after.

/** Returns the display name of a feature entry, whether it's a plain string or an object. */
export function featureName(f) {
  return typeof f === 'string' ? f : f.name;
}

/** True if the feature entry is an optional/variant rule (TCE etc.), not base PHB content. */
export function isOptionalFeature(f) {
  return typeof f !== 'string' && !!f.optional;
}

